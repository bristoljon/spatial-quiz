#!/usr/bin/env node
// Step 2 of building the "Oops!" round: take the picks exported from the
// picker, copy those clips into web/public/video/oops and write the round to
// shared/rounds/oops.js. Re-running replaces the round (and removes clips that
// are no longer picked).
//
//   node tools/oops/build-round.js --picks ~/Downloads/picks.json [--points 12] [--time 20]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const args = {};
for (let i = 2; i < process.argv.length; i += 2) args[process.argv[i].replace(/^--/, '')] = process.argv[i + 1];
if (!args.picks) {
  console.error('Usage: node tools/oops/build-round.js --picks <picks.json from the picker>');
  process.exit(1);
}
const work = path.resolve(args.work ?? path.join(here, 'work'));
const points = Number(args.points ?? 12);
const timeLimit = Number(args.time ?? 20);

const picks = JSON.parse(fs.readFileSync(args.picks.replace(/^~(?=\/)/, process.env.HOME), 'utf8'));
const candidates = new Map(JSON.parse(fs.readFileSync(path.join(work, 'candidates.json'), 'utf8')).map((c) => [c.id, c]));
const outDir = path.join(root, 'web/public/video/oops');
fs.mkdirSync(outDir, { recursive: true });

const questions = picks.map((p, i) => {
  const c = candidates.get(p.id);
  if (!c) throw new Error(`${p.id} isn't in ${work}/candidates.json`);
  if (!(p.px >= 0 && p.px <= c.width && p.py >= 0 && p.py <= c.height)) throw new Error(`${p.id}: answer (${p.px}, ${p.py}) is off the ${c.width}x${c.height} clip`);
  fs.copyFileSync(path.join(work, 'clips', `${c.id}.mp4`), path.join(outDir, `${c.id}.mp4`));
  return {
    id: `oops${i + 1}`, type: 'video', points, timeLimit,
    prompt: p.prompt,
    video: { src: `/video/oops/${c.id}.mp4`, width: c.width, height: c.height, pauseAt: p.pauseAt },
    answer: { px: p.px, py: p.py, label: 'Ends up here' },
    exact: 0.04, zeroAt: 0.3,
    note: `From the Oops! dataset (Epstein, Chen & Vondrick, CVPR 2020): ${c.source}`,
  };
});

// Clips from an earlier build that are no longer in the round.
const keep = new Set(questions.map((q) => path.basename(q.video.src)));
for (const f of fs.readdirSync(outDir)) if (f.endsWith('.mp4') && !keep.has(f)) fs.rmSync(path.join(outDir, f));

const body = questions.map((q) => `    ${JSON.stringify(q)},`).join('\n');
fs.writeFileSync(path.join(root, 'shared/rounds/oops.js'), `// Generated by tools/oops/build-round.js from picks made in the picker. Edit
// freely, but a rebuild overwrites it. Clips are in web/public/video/oops,
// trimmed from the Oops! dataset (https://oops.cs.columbia.edu), which is for
// non-commercial use.
export const oopsRound = {
  id: 'oops',
  title: 'Oops!',
  questions: [
${body}
  ],
};
`);
const bytes = questions.reduce((n, q) => n + fs.statSync(path.join(root, 'web/public', q.video.src)).size, 0);
console.log(`Wrote ${questions.length} questions to shared/rounds/oops.js; clips total ${(bytes / 1e6).toFixed(1)} MB (every phone preloads them).`);
