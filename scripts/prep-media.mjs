// Prepares quiz images:
//  - every "media:<file>" in shared/quiz.js is resized into public/m/<hash>.jpg
//  - every reveal question gets N zoom stages, tightest first
//  - missing source files get a labelled placeholder so the quiz still runs
// Output names are content hashes, so players can't guess the full image
// from a cropped stage's URL. Writes shared/media-manifest.js for the functions.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';
import { quiz } from '../shared/quiz.js';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const SRC = path.join(root, 'quiz-media');
const OUT = path.join(root, 'public', 'm');
const SALT = process.env.MEDIA_SALT || 'five-valleys';

await fs.rm(OUT, { recursive: true, force: true });
await fs.mkdir(OUT, { recursive: true });

const id = (...parts) => crypto.createHash('sha256').update(SALT + parts.join('|')).digest('hex').slice(0, 16);
const missing = [];

async function load(file) {
  const p = path.join(SRC, file);
  try {
    await fs.access(p);
    return sharp(p).rotate(); // honour EXIF orientation
  } catch {
    missing.push(file);
    const hue = [...file].reduce((a, c) => a + c.charCodeAt(0), 0) % 360;
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="1000">
      <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
        <stop offset="0" stop-color="hsl(${hue},45%,35%)"/><stop offset="1" stop-color="hsl(${(hue + 60) % 360},45%,20%)"/>
      </linearGradient></defs>
      <rect width="1600" height="1000" fill="url(#g)"/>
      ${Array.from({ length: 40 }, (_, i) => `<circle cx="${(i * 397) % 1600}" cy="${(i * 211) % 1000}" r="${20 + (i * 13) % 90}" fill="white" opacity="0.06"/>`).join('')}
      <text x="800" y="470" font-family="sans-serif" font-size="64" fill="white" text-anchor="middle" font-weight="bold">PLACEHOLDER</text>
      <text x="800" y="560" font-family="monospace" font-size="44" fill="white" text-anchor="middle" opacity="0.85">quiz-media/${file}</text>
    </svg>`;
    return sharp(Buffer.from(svg));
  }
}

const manifest = { files: {}, reveal: {} };

function collectRefs(obj, out = new Set()) {
  if (typeof obj === 'string' && obj.startsWith('media:')) out.add(obj.slice(6));
  else if (Array.isArray(obj)) obj.forEach((x) => collectRefs(x, out));
  else if (obj && typeof obj === 'object') Object.values(obj).forEach((x) => collectRefs(x, out));
  return out;
}

const revealQs = quiz.rounds.flatMap((r) => r.questions).filter((q) => q.type === 'reveal');

// plain media (options, question images)
const plainRefs = collectRefs(quiz.rounds.flatMap((r) => r.questions).map((q) => (q.type === 'reveal' ? { ...q, media: null } : q)));
for (const file of plainRefs) {
  const img = await load(file);
  const buf = await img.resize({ width: 900, height: 700, fit: 'inside', withoutEnlargement: true }).jpeg({ quality: 82 }).toBuffer();
  const name = `${id(file, 'plain')}.jpg`;
  await fs.writeFile(path.join(OUT, name), buf);
  manifest.files[file] = { url: `/m/${name}` };
}

// reveal stages
for (const q of revealQs) {
  const file = q.media.slice(6);
  const base = await (await load(file)).toBuffer();
  const meta = await sharp(base).metadata();
  const W = meta.width, H = meta.height;
  const n = q.stages || 5;
  const fx = q.focus?.x ?? 0.5, fy = q.focus?.y ?? 0.5;
  const minZoom = q.minZoom || 0.07; // fraction of the full width visible at stage 0
  const stages = [];
  for (let s = 0; s < n; s++) {
    // geometric progression from minZoom to 1
    const z = s === n - 1 ? 1 : minZoom * Math.pow(1 / minZoom, s / (n - 1));
    const cw = Math.max(16, Math.round(W * z)), ch = Math.max(10, Math.round(H * z));
    const left = Math.round(Math.min(Math.max(fx * W - cw / 2, 0), W - cw));
    const top = Math.round(Math.min(Math.max(fy * H - ch / 2, 0), H - ch));
    const buf = await sharp(base).extract({ left, top, width: cw, height: ch })
      .resize({ width: 1400, height: Math.round(1400 * H / W), fit: 'fill', kernel: s === 0 ? 'nearest' : 'lanczos3' })
      .jpeg({ quality: 80 }).toBuffer();
    const name = `${id(q.id, file, s)}.jpg`;
    await fs.writeFile(path.join(OUT, name), buf);
    stages.push(`/m/${name}`);
  }
  manifest.reveal[q.id] = { stages, full: stages[stages.length - 1] };
}

await fs.writeFile(path.join(root, 'shared', 'media-manifest.js'),
  `// generated by scripts/prep-media.mjs - do not edit\nexport default ${JSON.stringify(manifest, null, 2)};\n`);

console.log(`prep-media: ${Object.keys(manifest.files).length} images, ${revealQs.length} reveal sets`);
if (missing.length) console.log(`prep-media: placeholders used for missing files in quiz-media/:\n  ${missing.join('\n  ')}`);
